import math
def sqaure_root(num):
    from math import sqrt
    print(f"Sqaure root: {sqrt(num)}")
def log(num):
    from math import log
    print(f"Logarithmic: {log(num)}")
def sine(num):
    from math import sin
    print(f"Sine:{sin(num)}")

number=int(input("Enter a number:"))
sqaure_root(number)
log(number)
sine(number)
